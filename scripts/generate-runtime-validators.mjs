#!/usr/bin/env node

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const outputFile = join(root, "mcp", "generated", "runtime-validators.mjs");
const specs = Object.freeze([
  Object.freeze({ exportName: "validateEvidencePacket", file: "runtime-evidence-packet-v1.schema.json" }),
  Object.freeze({ exportName: "validateDebatePacket", file: "runtime-debate-packet-v1.schema.json" }),
  Object.freeze({ exportName: "validatePortfolioManagerPacket", file: "runtime-portfolio-manager-packet-v1.schema.json" }),
  Object.freeze({ exportName: "validateMethodVoice", file: "runtime-method-voice-v1.schema.json" }),
]);

function schemaBytes(spec) {
  return readFileSync(join(root, "schemas", spec.file), "utf8");
}

function digest() {
  const hash = createHash("sha256");
  for (const spec of specs) hash.update(`${spec.file}\0${schemaBytes(spec)}\0`);
  return hash.digest("hex");
}

export function generatedSource() {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: true,
    validateFormats: false,
    coerceTypes: false,
    useDefaults: false,
    removeAdditional: false,
    code: { source: true, esm: true, optimize: 2 },
  });
  const exports = {};
  for (const spec of specs) {
    const schema = JSON.parse(schemaBytes(spec));
    ajv.addSchema(schema);
    exports[spec.exportName] = schema.$id;
  }
  const compiled = standaloneCode(ajv, exports);
  if (/from\s+["']ajv\/|require\(["']ajv\//u.test(compiled)) {
    throw new Error("standalone validators unexpectedly retain an Ajv runtime import");
  }
  return [
    "// Generated by scripts/generate-runtime-validators.mjs. Do not edit by hand.",
    `// schema_bundle_sha256=${digest()}`,
    "// Runtime imports are intentionally forbidden: Codex marketplace installs do not run npm install.",
    compiled.trim(),
    "",
  ].join("\n");
}

export function main(args = process.argv.slice(2)) {
  const write = args.includes("--write");
  const check = args.includes("--check");
  if (write === check) throw new Error("choose exactly one of --write or --check");
  const expected = generatedSource();
  if (write) {
    mkdirSync(dirname(outputFile), { recursive: true });
    writeFileSync(outputFile, expected);
    process.stdout.write(`runtime-schema: wrote ${outputFile}\n`);
    return 0;
  }
  if (!existsSync(outputFile) || readFileSync(outputFile, "utf8") !== expected) {
    process.stderr.write("runtime-schema: generated validators are stale; run npm run schemas:generate\n");
    return 1;
  }
  process.stdout.write(`runtime-schema: ${specs.length} standalone validators are current\n`);
  return 0;
}

const invoked = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) {
  try {
    process.exitCode = main();
  } catch (error) {
    process.stderr.write(`runtime-schema failed: ${error.message}\n`);
    process.exitCode = 1;
  }
}
